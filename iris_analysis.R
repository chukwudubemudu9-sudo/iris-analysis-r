# DTS 211 - Analysis of the Iris Dataset in R
# Run from this folder: Rscript iris_analysis.R
suppressPackageStartupMessages(library(class))
dir.create("results", showWarnings=FALSE)
data(iris, package="datasets")
print(head(iris)); str(iris); print(summary(iris))
cat("Missing values:", sum(is.na(iris)), "\nDuplicates:", sum(duplicated(iris)), "\n")
print(table(iris$Species))
x <- iris[,1:4]
stats <- data.frame(Feature=names(x), Mean=sapply(x,mean), Median=sapply(x,median), SD=sapply(x,sd), Min=sapply(x,min), Max=sapply(x,max))
print(stats)
write.csv(stats,"results/summary.csv",row.names=FALSE)
by_species <- aggregate(x, list(Species=iris$Species), function(z)c(mean=mean(z),median=median(z),sd=sd(z)))
print(by_species)
write.csv(by_species,"results/summary_by_species.csv",row.names=FALSE)
cols <- c("#0072B2", "#D55E00", "#009E73")
png("results/pairplot.png",width=1400,height=1300,res=160)
pairs(x,col=cols[iris$Species],pch=19,oma=c(5,0,4,0))
mtext("Iris scatterplot matrix (cm)",side=3,outer=TRUE,line=1)
par(fig=c(0,1,0,0.065),mar=c(0,0,0,0),new=TRUE);plot.new()
legend("center",legend=levels(iris$Species),col=cols,pch=19,horiz=TRUE,bty="n");dev.off()
png("results/boxplots.png",width=1400,height=1000,res=160)
par(mfrow=c(2,2),mar=c(4,4,3,1))
for(n in names(x))boxplot(iris[[n]]~iris$Species,col=cols,main=n,xlab="Species",ylab="Measurement (cm)")
dev.off()
png("results/histograms.png",width=1400,height=1000,res=160)
par(mfrow=c(2,2),mar=c(4,4,3,1))
for(n in names(x))hist(x[[n]],breaks=15,col="#90C3D4",border="white",main=n,xlab="Measurement (cm)")
dev.off()
png("results/correlation.png",width=1200,height=1050,res=160)
par(mar=c(7,7,4,2));cr<-cor(x)
image(1:4,1:4,t(cr[4:1,]),col=colorRampPalette(c("#B2182B","white","#2166AC"))(100),zlim=c(-1,1),axes=FALSE,xlab="",ylab="",main="Feature correlations")
axis(1,1:4,labels=colnames(cr),las=2);axis(2,1:4,labels=rownames(cr)[4:1],las=2)
for(i in 1:4)for(j in 1:4)text(i,j,sprintf("%.2f",cr[5-j,i]))
dev.off()
# Stratified 70/30 split: 35 training and 15 test flowers per species.
set.seed(42)
train_idx <- sort(unlist(lapply(split(seq_len(nrow(iris)),iris$Species),function(ids)sample(ids,35))))
train <- x[train_idx,]; test <- x[-train_idx,]
y_train<-iris$Species[train_idx];y_test<-iris$Species[-train_idx]
# Fit standardisation on training data only.
center<-sapply(train,mean);spread<-sapply(train,sd)
train_z<-scale(train,center=center,scale=spread)
test_z<-scale(test,center=center,scale=spread)
# k is specified before examining the test set.
k<-5L
set.seed(42)
pred<-knn(train_z,test_z,y_train,k=k)
cm<-table(Actual=y_test,Predicted=pred)
accuracy<-mean(pred==y_test)
cat("\nk =",k," Test accuracy =",accuracy,"\n");print(cm)
write.csv(as.data.frame.matrix(cm),"results/confusion_matrix.csv")
write.csv(data.frame(k=k,accuracy=accuracy,train_n=nrow(train),test_n=nrow(test)),"results/metrics.csv",row.names=FALSE)
write.csv(data.frame(row=seq_len(nrow(iris)),set=ifelse(seq_len(nrow(iris))%in%train_idx,"train","test")),"results/split.csv",row.names=FALSE)
png("results/model.png",width=1100,height=1000,res=160)
par(mar=c(5,8,4,2));image(1:3,1:3,t(cm[3:1,]),col=colorRampPalette(c("white","#0072B2"))(100),axes=FALSE,xlab="Predicted species",ylab="",main=sprintf("Test confusion matrix: k = %d, accuracy = %.1f%%",k,100*accuracy))
axis(1,1:3,labels=colnames(cm));axis(2,1:3,labels=rownames(cm)[3:1],las=2)
mtext("Actual species",side=2,line=6)
for(i in 1:3)for(j in 1:3)text(i,j,cm[4-j,i],col=if(cm[4-j,i]>7)"white" else "black")
dev.off()
capture.output(sessionInfo(),file="results/sessionInfo.txt")
